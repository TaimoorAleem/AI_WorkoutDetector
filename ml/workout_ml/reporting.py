"""Plots and the generated baseline report."""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")  # headless: pipeline code never opens a window

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402


def plot_confusion(cm, classes, path, title):
    """Save a confusion-matrix heat map (counts, row-normalised colours) and close the figure."""
    cm = np.asarray(cm)
    row_sums = cm.sum(axis=1, keepdims=True)
    norm = np.divide(cm, row_sums, out=np.zeros(cm.shape, dtype=float), where=row_sums > 0)
    fig, ax = plt.subplots(figsize=(6, 5))
    try:
        im = ax.imshow(norm, cmap="Blues", vmin=0, vmax=1)
        ax.set_xticks(range(len(classes)), classes, rotation=45, ha="right")
        ax.set_yticks(range(len(classes)), classes)
        ax.set_xlabel("Predicted")
        ax.set_ylabel("True")
        ax.set_title(title, fontsize=9)
        for i in range(cm.shape[0]):
            for j in range(cm.shape[1]):
                ax.text(
                    j,
                    i,
                    int(cm[i, j]),
                    ha="center",
                    va="center",
                    color="white" if norm[i, j] > 0.5 else "black",
                    fontsize=8,
                )
        fig.colorbar(im, ax=ax, fraction=0.046, label="row fraction")
        fig.tight_layout()
        fig.savefig(path, dpi=120)
    finally:
        plt.close(fig)


def pm(mean, std, digits=3):
    return f"{mean:.{digits}f} ± {std:.{digits}f}"


def md_table(df, index=False):
    """Render a DataFrame as a GitHub markdown table (no tabulate dependency)."""
    if index:
        df = df.reset_index()
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join(_cell(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


def _cell(v):
    if isinstance(v, float):
        return "n/a" if np.isnan(v) else f"{v:.3f}"
    return str(v)


def leaderboard_table(leaderboard):
    """Leaderboard (sorted) as display DataFrame with mean ± std strings."""
    out = pd.DataFrame(
        {
            "rank": range(1, len(leaderboard) + 1),
            "feature_set": leaderboard["feature_set"].to_numpy(),
            "model": leaderboard["model"].to_numpy(),
            "n_features": leaderboard["n_features"].to_numpy(),
            "window acc": [
                pm(m, s)
                for m, s in zip(
                    leaderboard["lopo_window_acc_mean"], leaderboard["lopo_window_acc_std"]
                )
            ],
            "window macro-F1": [
                pm(m, s)
                for m, s in zip(
                    leaderboard["lopo_window_macro_f1_mean"],
                    leaderboard["lopo_window_macro_f1_std"],
                )
            ],
            "set acc": [
                pm(m, s)
                for m, s in zip(leaderboard["lopo_set_acc_mean"], leaderboard["lopo_set_acc_std"])
            ],
        }
    )
    return out


def render_report(
    *,
    leaderboard,
    best,
    pooled_cm,
    rep_summary,
    parent_run_id,
    best_run_id,
    data_md5,
    n_sets,
    n_windows,
    notes,
):
    """Markdown for docs/reports/phase0-baseline.md (tables only; interpretation is added later)."""
    classes = best.classes
    folds = best.folds
    fold_cols = ["fold", "test_participant", "n_sets", "n_windows"]
    fold_tab = folds[fold_cols + ["window_acc", "window_macro_f1", "set_acc"]].copy()
    mean_row = {c: "" for c in fold_tab.columns}
    mean_row.update({"fold": "mean ± std", "test_participant": ""})
    for c in ["window_acc", "window_macro_f1", "set_acc"]:
        mean_row[c] = pm(folds[c].mean(), folds[c].std(ddof=1))
    fold_tab = pd.concat([fold_tab.astype(object), pd.DataFrame([mean_row])], ignore_index=True)

    recall_cols = [f"recall_{c}" for c in classes]
    recall_tab = folds[["test_participant"] + recall_cols].copy()
    recall_tab.columns = ["test_participant"] + list(classes)

    cm_tab = pd.DataFrame(pooled_cm, columns=classes)
    cm_tab.insert(0, "true \\ predicted", classes)

    lines = [
        "# Phase 0 baseline: leakage-free LOPO evaluation",
        "",
        "Generated by `python -m workout_ml.pipeline`. Do not edit by hand.",
        "",
        f"- MLflow parent run ID: `{parent_run_id}`",
        f"- MLflow best-model (child) run ID: `{best_run_id}`",
        f"- Raw data md5 (`data/raw/MetaMotion.dvc`): `{data_md5}`",
        f"- Sets: {n_sets}, windows after preprocessing and window trimming: {n_windows}",
        f"- Best by mean LOPO window macro-F1 (tiebreak: set accuracy): "
        f"**{best.feature_set} / {best.model}**",
    ]
    lines += [f"- {n}" for n in notes]
    lines += [
        "",
        "## Leaderboard (mean ± std over the LOPO folds, sample std)",
        "",
        md_table(leaderboard_table(leaderboard)),
        "",
        f"## Per-fold detail: {best.feature_set} / {best.model}",
        "",
        md_table(fold_tab),
        "",
        "Per-class recall by held-out participant (n/a = class absent from that participant):",
        "",
        md_table(recall_tab),
        "",
        "## Pooled confusion matrix (all folds' predictions, window level)",
        "",
        md_table(cm_tab),
        "",
        "## Rep counter (`workout_ml.reps`, non-rest sets)",
        "",
        "Expected reps are assumed from the load category (heavy = 5, medium = 10), not annotated. "
        "The counter's cutoffs were hand-tuned on this same data, so these numbers are "
        "optimistic.",
        "",
        (
            md_table(rep_summary.rename_axis("exercise").reset_index())
            if rep_summary is not None
            else "_Not computed._"
        ),
        "",
    ]
    return "\n".join(lines)
