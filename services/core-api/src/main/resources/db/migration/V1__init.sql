CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE users (
    id             uuid PRIMARY KEY,
    email          citext       NOT NULL UNIQUE,
    password_hash  text         NOT NULL,
    participant_id varchar(32)  NOT NULL,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    deleted_at     timestamptz
);

CREATE TABLE refresh_tokens (
    id          uuid PRIMARY KEY,
    user_id     uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id   uuid        NOT NULL,
    token_hash  char(64)    NOT NULL UNIQUE, -- SHA-256 hex; the raw token is never stored
    created_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz NOT NULL,
    rotated_at  timestamptz,
    revoked_at  timestamptz
);
CREATE INDEX refresh_tokens_family_idx ON refresh_tokens (family_id);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens (user_id);

-- Append-only history; the current consent is the latest row.
CREATE TABLE consents (
    id           uuid PRIMARY KEY,
    user_id      uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    training_use boolean     NOT NULL,
    recorded_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX consents_user_idx ON consents (user_id, recorded_at DESC);

CREATE TABLE devices (
    id            uuid PRIMARY KEY,
    user_id       uuid         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    manufacturer  varchar(64)  NOT NULL,
    model         varchar(64)  NOT NULL,
    sdk_int       integer,
    first_seen_at timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (user_id, model)
);

CREATE TABLE sessions (
    session_id     uuid PRIMARY KEY, -- generated by the watch
    user_id        uuid         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    device_id      uuid         NOT NULL REFERENCES devices (id),
    kind           varchar(16)  NOT NULL CHECK (kind IN ('gym', 'calibration')),
    status         varchar(16)  NOT NULL CHECK (status IN ('CREATED', 'UPLOADED', 'ANALYZING', 'ANALYZED', 'FAILED')),
    started_at     timestamptz  NOT NULL,
    duration_s     double precision,
    object_key     varchar(512) NOT NULL,
    sha256         char(64)     NOT NULL,
    size_bytes     bigint       NOT NULL,
    raw_format     integer      NOT NULL,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    uploaded_at    timestamptz,
    analyzed_at    timestamptz,
    failure_reason text
);
CREATE INDEX sessions_user_started_idx ON sessions (user_id, started_at DESC, session_id DESC);

CREATE TABLE labels (
    session_id uuid PRIMARY KEY REFERENCES sessions (session_id) ON DELETE CASCADE,
    document   jsonb       NOT NULL,
    version    integer     NOT NULL DEFAULT 1, -- ETag
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE segment_predictions (
    session_id         uuid             NOT NULL REFERENCES sessions (session_id) ON DELETE CASCADE,
    segment_id         integer          NOT NULL,
    model_version      varchar(128)     NOT NULL,
    kind               varchar(16)      NOT NULL,
    start_s            double precision NOT NULL,
    end_s              double precision NOT NULL,
    predicted_exercise varchar(16),
    predicted_kind     varchar(16),
    confidence         double precision,
    rep_count          integer,
    model_name         varchar(128),
    profile_id         varchar(128),
    transform_id       varchar(128),
    created_at         timestamptz      NOT NULL DEFAULT now(),
    PRIMARY KEY (session_id, segment_id, model_version)
);

-- Idempotent consumers: one row per handled event.
CREATE TABLE processed_events (
    event_id     uuid PRIMARY KEY,
    processed_at timestamptz NOT NULL DEFAULT now()
);

-- Transactional outbox. kind AMQP publishes to the broker; S3_DELETE removes a raw object
-- (account deletion). Rows are written in the same transaction as the state change.
CREATE TABLE outbox (
    id           uuid PRIMARY KEY, -- equals the event_id for AMQP rows
    kind         varchar(16)  NOT NULL CHECK (kind IN ('AMQP', 'S3_DELETE')),
    exchange     varchar(128),
    routing_key  varchar(128),
    payload      text         NOT NULL,
    user_id      uuid, -- no FK: lets account deletion drop unpublished rows
    created_at   timestamptz  NOT NULL DEFAULT now(),
    published_at timestamptz,
    attempts     integer      NOT NULL DEFAULT 0
);
CREATE INDEX outbox_pending_idx ON outbox (created_at) WHERE published_at IS NULL;
